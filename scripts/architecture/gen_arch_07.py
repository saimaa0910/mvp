        p(f"- **Primary Key Type:** {e['pk_type']} (Monotonically Sortable)")
        p("")
        p("#### 02.{idx:02d}.1 PostgreSQL DDL Specification Blueprint")
        p("```sql")
        p(f"CREATE TABLE public.{table_name} (")
